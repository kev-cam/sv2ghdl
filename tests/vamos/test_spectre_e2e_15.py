"""e2e 15 (docs/VAMOS_SPECTRE_DESIGN.md §11.2 item 15, phase 2): the checks of fixtures/spectre/e2e/
15_ug_opamp/ that its expect.json cannot say.

    cd tests/vamos && PYTHONDONTWRITEBYTECODE=1 python3 -m unittest test_spectre_e2e_15

The deck's operating point follows the UG 5.1.41 idiom (p.113): `readns="%C:r.dc" write="%C:r.dc"`, one
state file read and written by the same analysis.  §8.6 and §5.4: write= holds the full solution of the
analysis's first point, every net (hierarchical with `.`) and the vsource currents, with the two-line
header; a readns file that does not exist yet is a note, and the second run finds it.

TestStateFileIdiom (WSL; needs_flow, needs_cpp, needs_vacask)   two runs in one directory: deck.dc after
    the first, its header and entries; the missing-file note on the first run only
"""

import os
import re
import shutil
import unittest

import spectre_testlib
from spectre_testlib import SpectreCase, needs_cpp, needs_vacask, spectre_fixture  # noqa: E402
from vamos_testlib import ROOT  # noqa: E402

CASE = spectre_fixture("e2e", "15_ug_opamp")

needs_flow = getattr(spectre_testlib, "needs_flow", None) or unittest.skipUnless(
    os.path.isfile(os.path.join(ROOT, "vamos", "spectre", "flow.py")),
    "needs vamos/spectre/flow.py (phase 2)")

MISSING = re.compile(r"opPoint readns: state file \S*deck\.dc not found")


@needs_flow
@needs_cpp
class TestStateFileIdiom(SpectreCase):

    @needs_vacask
    def test_write_then_readns_the_same_file(self):
        d = os.path.join(self.tmp, "e2e15")
        shutil.copytree(CASE, d)
        first = self.run_spectre(d, "deck.scs", "-E", engine="vacask")
        self.assertRegex(first.stdout, MISSING, "the first run reads no deck.dc: a note (§5.4)")
        path = os.path.join(d, "deck.dc")
        self.assertTrue(os.path.isfile(path), "write=\"%C:r.dc\" wrote no deck.dc in the run's directory")
        with open(path, encoding="latin-1") as fh:
            lines = fh.read().splitlines()
        self.assertEqual(lines[0], "# State file generated by Spectre from circuit file 'deck.scs'")
        self.assertTrue(lines[1].startswith("# during 'opPoint' at "), lines[1])
        entries = dict(ln.split() for ln in lines[2:] if ln.strip())
        for name in ("out", "pout", "nout", "pvg", "A1.11", "A1.12", "Vdd:p", "Vss:p"):
            self.assertIn(name, entries, "deck.dc: no entry %s (the full solution, §5.4, §8.6)" % name)
        self.assertAlmostEqual(float(entries["Vdd:p"]), -6.20481e-4, delta=1e-7)
        names = [ln.split()[0] for ln in lines[2:] if ln.strip()]
        first_current = min(k for k, n in enumerate(names) if ":" in n)
        self.assertFalse([n for n in names[first_current:] if ":" not in n], "nets first, then currents (§8.6)")
        second = self.run_spectre(d, "deck.scs", "-E", engine="vacask")
        self.assertNotRegex(second.stdout, MISSING, "the second run reads the deck.dc the first one wrote")


if __name__ == "__main__":
    unittest.main()
