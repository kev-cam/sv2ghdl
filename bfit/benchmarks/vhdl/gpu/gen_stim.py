#!/usr/bin/env python3
# Emit stim_<ent>.h: LFSR input drive + output fold that replay gen_tb.py's
# testbench semantics bit-for-bit against a gen_statemachine model.
# usage: gen_stim.py <circuit.vhd> <entity> > stim_<entity>.h
import re, sys
src = open('/usr/local/src/sv2ghdl/bfit/benchmarks/vhdl/gen_tb.py').read()
ns = {}
exec(src[:src.index('def main')], ns)          # borrow load/entity_ports/parse
path, ent = sys.argv[1], sys.argv[2]
ports = ns['parse'](ns['entity_ports'](ns['load'](path), ent))
clk = next((p[0] for p in ports if p[0].lower() in ("clock", "clk")), None)
rst = next((p[0] for p in ports if p[0].lower() in ("reset", "rst")), None)
ins  = [p for p in ports if p[1] == "in"  and p[0] not in (clk, rst)]
outs = [p for p in ports if p[1] == "out"]
def rng(txt):   # "2**20-1 downto 0" / "0 to 7" -> (low, high)
    m = re.match(r'(.*?)\s+(downto|to)\s+(.*)$', txt.strip(), re.I | re.S)
    a, b = eval(m.group(1)), eval(m.group(3))
    return (b, a) if m.group(2).lower() == 'downto' else (a, b)
L = []
w = L.append
w('// AUTO-GENERATED by gen_stim.py for %s -- mirrors gen_tb.py' % ent)
w('#define STIM_NAME "%s"' % ent)
w('#define STIM_RST %s' % ('_' + rst.lower() if rst else 'STIM_NO_RESET'))
w('#define STIM_HAS_RST %d' % (1 if rst else 0))
if rst: w('SM_DEVICE static inline void stim_reset(inputs_t *in, int active) { in->_%s = active ? 1 : 0; }' % rst.lower())
w('SM_DEVICE static inline void stim_drive(uint32_t *lfsr, inputs_t *in) {')
w('  uint32_t l = *lfsr, fb;')
for nm, _, k in ins:
    n = 1 if k[0] in ("bit", "int") else k[3]
    w('  // %s : %s' % (nm, k))
    w('  for (int i = 0; i < %d; i++) { fb = ((l>>31)^(l>>21)^(l>>1)^l)&1u; l = (l<<1)|fb; }' % n)
    m = '_' + nm.lower()
    if k[0] == 'bit':
        w('  in->%s = l & 1u;' % m)
    elif k[0] == 'int':
        if k[1]:
            lo, hi = rng(k[1])
            w('  in->%s = (uint64_t)(uint32_t)(int32_t)(%d + (int32_t)((l & 0xffu) %% %d));' % (m, lo, hi - lo + 1))
        else:
            w('  in->%s = (uint64_t)(l & 0xffu);' % m)
    else:
        assert k[3] <= 64, 'wide vector input not supported: %s' % nm
        w('  in->%s = (uint64_t)(l & %s);' % (m, '0xffffffffu' if k[3] >= 32 else '0x%xu' % ((1 << k[3]) - 1)))
w('  *lfsr = l;')
w('}')
w('SM_DEVICE static inline uint64_t stim_fold(uint64_t r, const outputs_t *o) {')
for nm, _, k in outs:
    m = '_' + nm.lower()
    if k[0] == 'bit':
        w('  r = (r<<1)|(r>>63); r ^= (o->%s & 1u);' % m)
    elif k[0] == 'int':
        w('  r = (r<<1)|(r>>63); { int32_t v = (int32_t)(uint32_t)o->%s; int32_t mm = v %% 65536; if (mm < 0) mm += 65536; r ^= (uint64_t)mm; }' % m)
    else:
        w('  for (int i = %d; i >= 0; i--) { r = (r<<1)|(r>>63); r ^= (o->%s >> i) & 1u; }' % (k[3] - 1, m))
w('  return r;')
w('}')
print('\n'.join(L))
