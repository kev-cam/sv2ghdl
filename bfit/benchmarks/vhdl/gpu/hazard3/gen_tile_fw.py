#!/usr/bin/env python3
# gen_tile_fw.py - the split-render firmware source, generated at build time
# from upstream's sw/mandelbrot.c (verilator-hazard3-mandelbrot-testbench,
# "Copyright 2026 Can Joshua Lehmann", Apache-2.0).  Nothing of mandelbrot.c is
# stored in this kit; the output is a modified copy of the fetched file and
# carries its licence.  Part of the bfit GPU-farm kit (PolyForm NC 1.0.0).
#
# Only the LOOPS are restructured; the fixed-point math (fixed_*, complex_*),
# the pixel->c formula, the escape loop and the colour function are untouched
# text.  Edits, each matched exactly once against the pinned file:
#   1. void mandelbrot(uint32_t image[SIZE][SIZE])  ->  void mandelbrot_tile(uint32_t tile)
#   2. the y/x loop headers  ->  a loop over the tile's pixels,
#        for (size_t tk = 0; tk < TILE_K(tile); tk++) { size_t y = TILE_Y(tile, tk), x = TILE_X(tile, tk);
#      (same brace count; tile geometry: fw/tile_geom.h)
#   3. image[y][x] = <v>;  ->  tile_put(<v>);      (both stores: black and colour)
#   4. main() (zeroes the 4 MB image with memset, renders, used_image) is
#      removed; the runtime (fw/tile_rt.h for RV32, fw/tile_native.h for the
#      host golden) supplies main().  This is what drops the whole-image memset.
#   gen_tile_fw.py <checkout>/sw/mandelbrot.c > tile_mandelbrot.c
import re, sys

EDITS = [
    ('signature', 'literal', 'void mandelbrot(uint32_t image[SIZE][SIZE]) {', 'void mandelbrot_tile(uint32_t tile) {'),
    ('loops', 'literal',
     '  for (size_t y = 0; y < SIZE; y++) {\n    for (size_t x = 0; x < SIZE; x++) {\n',
     '  for (size_t tk = 0; tk < TILE_K(tile); tk++) {\n    { size_t y = TILE_Y(tile, tk), x = TILE_X(tile, tk);\n'),
    ('store black', 'literal', 'image[y][x] = 0; // black', 'tile_put(0); // black'),
    ('store colour', 'regex', r'image\[y\]\[x\] = (rgb\(.*\));', r'tile_put(\1);'),
    ('main', 'regex_s', r'\nint main\(\) \{\n.*?\n\}\n', '\n/* upstream main() (memset of the whole image, render, used_image) removed by gen_tile_fw.py:\n   the runtime supplies main() */\n'),
]


def main():
    src = open(sys.argv[1]).read()
    for title, kind, pat, rep in EDITS:
        if kind == 'literal':
            n = src.count(pat)
            if n == 1:
                src = src.replace(pat, rep)
        else:
            rx = re.compile(pat, re.S if kind == 'regex_s' else 0)
            n = len(rx.findall(src))
            if n == 1:
                src = rx.sub(lambda m: m.expand(rep), src)
        if n != 1:
            sys.stderr.write('gen_tile_fw: edit "%s": expected 1 match, found %d (not the pinned mandelbrot.c?)\n' % (title, n))
            return 1
    if 'image[' in src.split('void mandelbrot_tile')[1]:
        sys.stderr.write('gen_tile_fw: an image store survived\n')
        return 1
    sys.stdout.write('// GENERATED by bfit gpu/hazard3/gen_tile_fw.py from upstream sw/mandelbrot.c\n'
                     '// (verilator-hazard3-mandelbrot-testbench, Copyright 2026 Can Joshua Lehmann,\n'
                     '// Apache License 2.0): loops restructured into one tile, main() removed.\n'
                     + src)
    return 0


if __name__ == '__main__':
    sys.exit(main())
