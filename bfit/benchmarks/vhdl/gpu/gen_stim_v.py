#!/usr/bin/env python3
# Model-driven stimulus for SV/Verilog designs (RTLMeter cores): parse the gsm
# model's inputs_t/outputs_t, emit (a) stim_<d>.h for farm.cu and (b) a
# Verilator C++ testbench tb_<d>.cpp with the IDENTICAL LFSR order and fold,
# so the two can be checksum-compared.  Convention (differs from gen_tb.py):
# per input port, per 32-bit chunk (LSW first): advance the LFSR 32 steps and
# take its whole state (masked); 1-bit ports advance once and take bit 0.
# Fold: MSB-first rotate/xor over every output bit (same as gen_tb.py's fold).
# Reset ports = names matching (^|_)(rst|reset|resetn|rst_l|rst_n)...; a name
# ending in _l or _n (or resetn) is active-LOW.  Clock-like inputs are held 0.
#   gen_stim_v.py model.c <design> <clk-port> [reset-port,...] > stim_<d>.h ; writes tb_<d>.cpp alongside
import re, sys
model, name, clk = sys.argv[1], sys.argv[2], sys.argv[3]
rst_override = sys.argv[4].split(',') if len(sys.argv) > 4 and sys.argv[4] else None
src = open(model).read()
def members(struct):
    body = next(b for b, nm in re.findall(r'typedef struct \{(.*?)\} (\w+);', src, re.S) if nm == struct)
    out = []
    for line in body.splitlines():
        d = re.match(r'\s*(uint8_t|uint32_t|uint64_t|int)\s+(_[A-Za-z0-9_]+)(?:\[(\d+)\])?\s*;\s*//\s*(\d+) bits', line)
        if d: out.append((d.group(2), int(d.group(4)), int(d.group(3)) if d.group(3) else 0))
    return out
ins, outs = members('inputs_t'), members('outputs_t')
xm = re.search(r'sm_extra_clocks\[\] = \{([^}]*)\}', src)
extra = [x.strip().strip('"') for x in xm.group(1).split(',') if x.strip() and x.strip() != '0'] if xm else []
def is_rst(n):
    b = n[1:]
    if rst_override is not None: return b in rst_override
    return bool(re.match(r'^(i_)?(rst|reset)(_l|_n|n|_b)?$', b)) or b in ('dbg_rst_l',)
def is_clk(n): return n[1:] == clk or n[1:] in extra or re.match(r'^(i_)?(clk|clock)$', n[1:]) is not None or n[1:].startswith('jtag_')   # jtag_*: held 0 (TAP idle; negedge-tck flops are outside the 2-phase model, and RTLMeter never drives JTAG)
rsts = [n for n, _, _ in ins if is_rst(n)]
low  = {n: n.endswith('_l') or n.endswith('_n') or n.endswith('resetn') or n.endswith('_b') for n in rsts}
drive = [(n, w, a) for n, w, a in ins if not is_rst(n) and not is_clk(n)]
assert rsts, 'no reset port found among ' + str([n for n,_,_ in ins])
L = []; w = L.append
w('// AUTO-GENERATED by gen_stim_v.py from %s' % model)
w('#define STIM_NAME "%s"' % name); w('#define STIM_HAS_RST 1'); w('#define STIM_RST %s' % rsts[0])
if extra: w('#define STIM_CLKMASK 1u   // main clock only; extra clocks %s held at 0' % extra)
w('SM_DEVICE static inline void stim_reset(inputs_t *in, int active) {')
for n in rsts: w('  in->%s = active ? %d : %d;' % (n, 0 if low[n] else 1, 1 if low[n] else 0))
w('}')
w('SM_DEVICE static inline uint32_t lfsr32(uint32_t l, int n) { for (int i = 0; i < n; i++) { uint32_t fb = ((l>>31)^(l>>21)^(l>>1)^l)&1u; l = (l<<1)|fb; } return l; }')
w('SM_DEVICE static inline void stim_drive(uint32_t *lfsr, inputs_t *in) {')
w('  uint32_t l = *lfsr;')
for n, wd, arr in drive:
    if wd == 1: w('  l = lfsr32(l, 1); in->%s = l & 1u;' % n)
    elif arr:
        w('  for (int k = 0; k < %d; k++) { l = lfsr32(l, 32); in->%s[k] = l & ((k == %d && (%d %% 32)) ? ((1u << (%d %% 32)) - 1u) : 0xffffffffu); }' % (arr, n, arr - 1, wd, wd))
    else:
        nch = (wd + 31) // 32
        w('  { uint64_t v = 0; for (int k = 0; k < %d; k++) { l = lfsr32(l, 32); v |= (uint64_t)l << (32*k); } in->%s = v & %s; }' % (nch, n, 'UINT64_MAX' if wd >= 64 else '((UINT64_C(1) << %d) - 1)' % wd))
w('  *lfsr = l;'); w('}')
w('SM_DEVICE static inline uint64_t stim_fold(uint64_t r, const outputs_t *o) {')
for n, wd, arr in outs:
    if arr: w('  for (int i = %d; i >= 0; i--) { r = (r<<1)|(r>>63); r ^= (o->%s[i>>5] >> (i&31)) & 1u; }' % (wd - 1, n))
    else:   w('  for (int i = %d; i >= 0; i--) { r = (r<<1)|(r>>63); r ^= (o->%s >> i) & 1u; }' % (wd - 1, n))
w('  return r;'); w('}')
w('#ifndef __CUDACC__')
w('#include <stdio.h>')
w('static inline void stim_print(const outputs_t *o) {')
for n, wd, arr in outs:
    if arr: w('  printf("%s=");  for (int i = %d; i >= 0; i--) printf("%%08x", o->%s[i]); printf("\\n");' % (n[1:], arr - 1, n))
    else:   w('  printf("%s=%%llx\\n", (unsigned long long)o->%s);' % (n[1:], n))
w('}')
w('#endif')
print('\n'.join(L))
# ---- Verilator testbench with the same sequencing as farm.cu::run_instance ----
T = []; t = T.append
t('// AUTO-GENERATED by gen_stim_v.py — Verilator twin of farm.cu for %s' % name)
t('#include "V%s.h"' % name); t('#include "verilated.h"'); t('#include <cstdio>'); t('#include <cstdlib>'); t('#include <cstdint>'); t('#include <ctime>')
t('static uint32_t lfsr32(uint32_t l, int n) { for (int i = 0; i < n; i++) { uint32_t fb = ((l>>31)^(l>>21)^(l>>1)^l)&1u; l = (l<<1)|fb; } return l; }')
t('static double now(){ struct timespec ts; clock_gettime(CLOCK_MONOTONIC,&ts); return ts.tv_sec+1e-9*ts.tv_nsec; }')
t('static void set_reset(V%s *top, int active) {' % name)
for n in rsts: t('  top->%s = active ? %d : %d;' % (n[1:], 0 if low[n] else 1, 1 if low[n] else 0))
t('}')
t('static void drive(uint32_t *lfsr, V%s *top) {' % name); t('  uint32_t l = *lfsr;')
for n, wd, arr in drive:
    p = n[1:]
    if wd == 1: t('  l = lfsr32(l, 1); top->%s = l & 1u;' % p)
    elif arr:
        t('  for (int k = 0; k < %d; k++) { l = lfsr32(l, 32); top->%s[k] = l & ((k == %d && (%d %% 32)) ? ((1u << (%d %% 32)) - 1u) : 0xffffffffu); }' % (arr, p, arr - 1, wd, wd))
    else:
        nch = (wd + 31) // 32
        t('  { uint64_t v = 0; for (int k = 0; k < %d; k++) { l = lfsr32(l, 32); v |= (uint64_t)l << (32*k); } top->%s = v & %s; }' % (nch, p, 'UINT64_MAX' if wd >= 64 else '((UINT64_C(1) << %d) - 1)' % wd))
t('  *lfsr = l;'); t('}')
t('static uint64_t fold(uint64_t r, V%s *top) {' % name)
for n, wd, arr in outs:
    p = n[1:]
    if arr: t('  for (int i = %d; i >= 0; i--) { r = (r<<1)|(r>>63); r ^= (top->%s[i>>5] >> (i&31)) & 1u; }' % (wd - 1, p))
    else:   t('  for (int i = %d; i >= 0; i--) { r = (r<<1)|(r>>63); r ^= ((uint64_t)top->%s >> i) & 1u; }' % (wd - 1, p))
t('  return r;'); t('}')
t('static void print_outputs(V%s *top) {' % name)
for n, wd, arr in outs:
    p = n[1:]
    if arr: t('  printf("%s=");  for (int i = %d; i >= 0; i--) printf("%%08x", top->%s[i]); printf("\\n");' % (p, arr - 1, p))
    else:   t('  printf("%s=%%llx\\n", (unsigned long long)top->%s);' % (p, p))
t('}')
t('int main(int argc, char **argv) {')
t('  int cycles = argc > 1 ? atoi(argv[1]) : 100000; int dumpc = argc > 2 ? atoi(argv[2]) : -1; Verilated::commandArgs(argc, argv);')
t('  V%s *top = new V%s; uint32_t lfsr = 0x12345678u; uint64_t chk = 0;' % (name, name))
t('  top->%s = 0; set_reset(top, 1); top->eval();' % clk)
t('  for (int k = 0; k < 4; k++) { top->%s = 1; top->eval(); top->%s = 0; top->eval(); }' % (clk, clk))
t('  set_reset(top, 0);')
t('  double t0 = now();')
t('  for (int c = 1; c <= cycles; c++) {')
t('    top->eval(); chk = fold(chk, top);                       // clk low: comb settled on current inputs (+async reset), fold')
t('    if (c == dumpc) print_outputs(top);')
t('    top->%s = 1; top->eval(); top->%s = 0;                  // posedge with the OLD inputs' % (clk, clk))
t('    if ((c & 511) == 0) set_reset(top, 1); else if ((c & 511) == 2) set_reset(top, 0);')
t('    drive(&lfsr, top);                                       // new inputs land after the edge')
t('  }')
t('  double dt = now() - t0;')
t('  printf("VERILATOR design=%s cycles=%%d secs=%%.4f cyc_per_s=%%.4e CHK0=%%016llX\\n", cycles, dt, cycles/dt, (unsigned long long)chk);' % name)
t('  delete top; return 0; }')
open('tb_%s.cpp' % name, 'w').write('\n'.join(T) + '\n')
sys.stderr.write('stim: %d driven inputs, %d outputs, resets %s, clk %s, extra clocks held 0: %s\n' % (len(drive), len(outs), rsts, clk, extra))
