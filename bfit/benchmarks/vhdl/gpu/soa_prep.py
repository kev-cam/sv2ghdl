#!/usr/bin/env python3
# SoA farm prep: model.c + stim.h -> model_soa.c, stim_soa.h, soa_alloc.h
#  1. yosys/make_soa_model.py: every state/inputs/outputs member becomes an
#     [SM_N]-strided array indexed by sm_gid (stim.h is transformed with it so
#     in->/o-> accesses match).
#  2. here: the struct members become POINTERS into runtime-sized buffers so
#     SM_N is a runtime value (one binary, any instance count); sm_reset's
#     sizeof-memset is dropped (buffers are zeroed by the host); soa_alloc.h
#     gets a generated allocator listing every member's element type/count.
#   usage: soa_prep.py model.c stim.h   (writes alongside model.c)
import re, sys, subprocess, os
model, stim = sys.argv[1], sys.argv[2]
d = os.path.dirname(os.path.abspath(model)); os.chdir(d)
subprocess.check_call(['python3', '/usr/local/src/sv2ghdl/yosys/make_soa_model.py', os.path.basename(model), os.path.basename(stim)])
msoa = os.path.basename(model).replace('.c', '_soa.c'); ssoa = os.path.basename(stim).replace('.h', '_soa.h')
s = open(msoa).read()
members = {}   # struct -> [(type, name, per-instance count)]
def fix(m):
    body, nm = m.group(1), m.group(2); out = []
    if nm not in ('state_t', 'inputs_t', 'outputs_t'): return m.group(0)   # coverage structs etc. untouched
    members[nm] = []
    for line in body.split('\n'):
        d2 = re.match(r'(\s*)(uint8_t|uint32_t|uint64_t|int)\s+(_[A-Za-z0-9_]+)\[(.*?)\];(.*)$', line)
        if d2:
            cnt = d2.group(4)
            n = '1' if cnt == 'SM_N' else cnt.replace('*SM_N', '')
            members[nm].append((d2.group(2), d2.group(3), n))
            out.append('%s%s *%s;%s' % (d2.group(1), d2.group(2), d2.group(3), d2.group(5)))
        else: out.append(line)
    return 'typedef struct {' + '\n'.join(out) + '} ' + nm + ';'
s = re.sub(r'typedef struct \{(.*?)\} (\w+);', fix, s, flags=re.S)
# sm_reset: drop the whole-struct memset (would zero the pointers)
s, n1 = re.subn(r'\n\s*for \(unsigned long _zi = 0; _zi < sizeof\(state_t\); _zi\+\+\)\n\s*\(\(char\*\)s\)\[_zi\] = 0;', '\n    /* SoA: buffers zeroed by host */', s)
# SM_N / sm_gid are provided by the harness (runtime) before the model is included
s = s.replace('#ifndef SM_N\n#define SM_N 1\n#endif\n#ifndef sm_gid\n#define sm_gid 0\n#endif', '/* SM_N / sm_gid defined by the harness */')
open(msoa, 'w').write(s)
A = ['/* generated by soa_prep.py: per-member buffer allocation (elements per instance) */',
     '#define SOA_MEMBERS(X) \\']
for st in ('state_t', 'inputs_t', 'outputs_t'):
    for t, nm, n in members[st]:
        A.append('  X(%s, %s, %s, %s) \\' % (st, t, nm, n))
A.append('  /* end */')
A.append('static const size_t soa_bytes_per_instance = 0' + ''.join(' + sizeof(%s)*(%s)' % (t, n) for st in ('state_t','inputs_t','outputs_t') for t, nm, n in members[st]) + ';')
open('soa_alloc.h', 'w').write('\n'.join(A) + '\n')
sys.stderr.write('soa_prep: %s members state/in/out = %d/%d/%d; memset removed=%d\n' % (msoa, len(members['state_t']), len(members['inputs_t']), len(members['outputs_t']), n1))
